// Generate the browser compatibility asset; never edit its bundled output.
import {build} from 'esbuild';
import fs from 'node:fs';
const output = new URL('../houdini/python3.11libs/dsh_iterator_polyfill.js', import.meta.url);
// DSH's model selector and model-settings page call Array#toSorted during
// their first render. QtWebEngine's Chromium 108 needs this before app boot.
const result = await build({stdin:{contents:"import 'core-js/actual/iterator'; import 'core-js/actual/array/to-sorted';",resolveDir:process.cwd()},
  bundle:true,write:false,format:'iife',platform:'browser',target:'chrome108',minify:true,
  legalComments:'inline',banner:{js:'// Generated by tools/gen-web-polyfills.mjs; core-js (MIT), see dsh_iterator_polyfill.LICENSE.'}});
const content = result.outputFiles[0].text;
const license = fs.readFileSync(new URL('../node_modules/core-js/LICENSE', import.meta.url),'utf8');
for (const [file, text] of [[output,content],[new URL('../houdini/python3.11libs/dsh_iterator_polyfill.LICENSE',import.meta.url),license]]) {
  if(process.argv.includes('--check')) {
    if(!fs.existsSync(file) || fs.readFileSync(file,'utf8').replaceAll('\r\n','\n')!==text.replaceAll('\r\n','\n')) throw Error('Web polyfill generated asset drift: '+file);
  } else if(!fs.existsSync(file) || fs.readFileSync(file,'utf8')!==text) fs.writeFileSync(file,text);
}
console.log('Web runtime compatibility asset in sync');

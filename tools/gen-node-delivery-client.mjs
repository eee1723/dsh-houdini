import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import ts from "typescript";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (file) => fs.readFileSync(path.resolve(root, file), "utf8").replaceAll("\r\n", "\n");

function initializer(file, name) {
  const source = ts.createSourceFile(file, read(file), ts.ScriptTarget.Latest, true);
  let found;
  function visit(node) {
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && node.name.text === name) found = node.initializer;
    ts.forEachChild(node, visit);
  }
  visit(source);
  if (!found) throw new Error(`${file}: missing ${name}`);
  const js = ts.transpile(`const value = ${found.getText(source)}; value;`);
  return vm.runInNewContext(js, undefined, { timeout: 1000 });
}

export function generatedNodeDeliveryFactory() {
  const shared = ts.transpile(read("src/node-delivery-record.ts"), { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext })
    .replace(/^export /gm, "");
  return read("client/node-delivery.js").replace("/* NODE_DELIVERY_RECORD */", shared);
}

export function generatedNodeDeliveryBlock() {
  const adapter = ts.createSourceFile("src/dsh-adapter.ts", read("src/dsh-adapter.ts"), ts.ScriptTarget.Latest, true);
  const decoder = adapter.statements.find(node => ts.isFunctionDeclaration(node) && node.name?.text === "liveJobResult");
  if (!decoder) throw new Error("Missing canonical live-job decoder");
  const liveJobDecoder = ts.transpile(decoder.getText(adapter), { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext })
    .replace(/^export /m, "");
  const source = generatedNodeDeliveryFactory();
  return `// >>> houdini-node-delivery (generated by tools/gen-node-delivery-client.mjs — do not edit)
    var LIVE_JOB_KIND = ${JSON.stringify(initializer("src/dsh-adapter.ts", "LIVE_JOB_KIND"))};
    var LIVE_JOB_RESULT = ${JSON.stringify(initializer("src/dsh-adapter.ts", "LIVE_JOB_RESULT"))};
    ${liveJobDecoder.trim()}
    var nodeDeliveryFactory = (${source.trim()});
    // <<< houdini-node-delivery`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const file = path.join(root, "client.js");
  const old = read(file);
  const deliveryPattern = /\/\/ >>> houdini-node-delivery[^\n]*\n[\s\S]*?\/\/ <<< houdini-node-delivery/;
  if (!deliveryPattern.test(old)) throw new Error("Missing node delivery generation markers");
  const next = old
    .replace(/\/\/ >>> houdini-trace[^\n]*\n[\s\S]*?\/\/ <<< houdini-trace/, "")
    .replace(/\/\/ >>> houdini-catalog[^\n]*\n[\s\S]*?\/\/ <<< houdini-catalog/, "")
    .replace(deliveryPattern, () => generatedNodeDeliveryBlock());
  if (process.argv.includes("--check")) {
    if (next !== old) throw new Error("Node delivery bundle/source drifted; run npm run build");
  } else if (next !== old) fs.writeFileSync(file, next);
  console.log("Node delivery client in sync");
}

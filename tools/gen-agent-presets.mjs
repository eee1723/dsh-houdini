/** Compose our personas and Houdini layer onto the qualified DSH standard. */
import fs from 'node:fs'
import path from 'node:path'
import {createRequire} from 'node:module'
import {fileURLToPath} from 'node:url'

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..')
const packageFile=path.join(root,'node_modules/@deepseek-ai/dsh-agent-presets/package.json')
const require=createRequire(packageFile), yaml=require('js-yaml')
class Expression {constructor(text){this.text=text}}
const expression=new yaml.Type('tag:yaml.org,2002:js',{kind:'scalar',instanceOf:Expression,
  construct:text=>new Expression(text),represent:value=>value.text})
const schema=yaml.DEFAULT_SCHEMA.extend([expression])
const standard=yaml.load(fs.readFileSync(path.join(path.dirname(packageFile),'presets/standard/agent.cordis.yml'),'utf8'),{schema})
const check=process.argv.includes('--check')
for(const name of ['houdini','houdini-dev','houdini-product']) {
  const persona=name==='houdini-product'?'houdini':name
  const entries=standard.filter(entry=>!['persona','tool-plugin-manager'].includes(entry.id))
  entries.unshift({id:'persona',name:'@deepseek-ai/dsh-persona',config:{
    prefix:fs.readFileSync(path.join(root,'presets',persona,'persona.md'),'utf8').trim()}})
  entries.splice(entries.findIndex(entry=>entry.id==='agent-instructions')+1,0,{id:'houdini',name:'dsh-houdini',config:{
    ...(name==='houdini-product'?{productMode:true}:{}),bridgeUrl:'http://127.0.0.1:8765',requestTimeoutMs:120000,
    executorRegistry:new Expression('process.env.DSH_HOUDINI_EXECUTOR_REGISTRY || undefined')}})
  const content='# Generated by tools/gen-agent-presets.mjs from qualified DSH and persona.md.\n'
    +yaml.dump(entries,{schema,lineWidth:-1,noRefs:true})
  const destination=path.join(root,'presets',name,'agent.cordis.yml')
  if(check) {
    if(!fs.existsSync(destination)||fs.readFileSync(destination,'utf8')!==content) throw Error('Preset is stale: '+name)
  } else {fs.mkdirSync(path.dirname(destination),{recursive:true});fs.writeFileSync(destination,content)}
}
const productFile=path.join(root,'presets/houdini-product/preset.yml')
const productMetadata='# Generated by tools/gen-agent-presets.mjs\nname: Houdini 产品建模\ndescription: 聚焦可编辑产品模型、细节与控制；产品要求可按需记录。\n'
if(check) {
  if(!fs.existsSync(productFile)||fs.readFileSync(productFile,'utf8')!==productMetadata) throw Error('Product preset metadata is stale')
} else fs.writeFileSync(productFile,productMetadata)
console.log(check?'Agent presets are in sync':'Agent presets generated')

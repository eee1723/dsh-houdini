/** Register one scoped Houdini preset on the qualified DSH Web composition. */
import fs from 'node:fs'
import path from 'node:path'
import {createRequire} from 'node:module'
import {fileURLToPath} from 'node:url'

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..')
const packageFile=path.join(root,'node_modules/@deepseek-ai/dsh-web-app/package.json')
const require=createRequire(packageFile), yaml=require('js-yaml')
class Expression {constructor(text){this.text=text}}
const expression=new yaml.Type('tag:yaml.org,2002:js',{kind:'scalar',instanceOf:Expression,
  construct:text=>new Expression(text),represent:value=>value.text})
const schema=yaml.DEFAULT_SCHEMA.extend([expression])
const standardPatch=yaml.load(fs.readFileSync(path.join(path.dirname(packageFile),'presets/standard.patch.yml'),'utf8'),{schema})
const standard=standardPatch[0].insert[0].config.plugins
const check=process.argv.includes('--check')
const directory=path.join(root,'presets/houdini')
const metadata=yaml.load(fs.readFileSync(path.join(directory,'preset.yml'),'utf8'))
const plugins=standard.filter(entry=>!['persona','tool-plugin-manager'].includes(entry.id))
plugins.unshift({id:'persona',name:'@deepseek-ai/dsh-persona',config:{
  prefix:fs.readFileSync(path.join(directory,'persona.md'),'utf8').trim()}})
plugins.splice(plugins.findIndex(entry=>entry.id==='agent-instructions')+1,0,{id:'houdini',name:'dsh-houdini',config:{
  bridgeUrl:new Expression("process.env.DSH_HOUDINI_BRIDGE_URL || 'http://127.0.0.1:8765'"),
  requestTimeoutMs:120000,
  executorRegistry:new Expression('process.env.DSH_HOUDINI_EXECUTOR_REGISTRY || undefined')}})
const patch=[...['standard','ptc','minimal','cordis'].map(id=>({id:'preset-'+id,disabled:true})),
  {id:'agent-preset-registry',config:{default:'houdini'}},
  {insert:[{id:'preset-houdini',name:'@deepseek-ai/dsh-agent-preset',config:{
    id:'houdini',name:metadata.name,description:metadata.description,order:1,plugins}}]}]
const content='# Generated by tools/gen-agent-presets.mjs from qualified DSH and persona.md.\n'
  +yaml.dump(patch,{schema,lineWidth:-1,noRefs:true})
const destination=path.join(directory,'cordis.patch.yml')
if(check) {
  if(!fs.existsSync(destination)||fs.readFileSync(destination,'utf8')!==content) throw Error('Houdini preset is stale')
} else fs.writeFileSync(destination,content)
console.log(check?'Agent presets are in sync':'Agent presets generated')

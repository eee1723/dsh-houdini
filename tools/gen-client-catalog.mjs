#!/usr/bin/env node
// 构建期生成器：把 docs/tool-design.md（词表唯一真相源）解析出的目录注入
// client.js 的标记区（>>> houdini-catalog ... <<< houdini-catalog）。
//
// 为什么走生成而不是运行时拉取：client.js 是手写 CJS 静态 bundle，require
// 只认平台 seed word（没有 host RPC 符号，见 dsh-client-web getStaticModules），
// webserver 也不 serve 插件目录——目录只能内联。由本脚本从真相源机械派生，
// 挂在 `npm run build` 里，手改标记区会被下次构建覆盖，因此不漂移。
import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadCatalog } from './catalog-lib.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DOC = path.join(ROOT, 'docs', 'tool-design.md');
const CLIENT = path.join(ROOT, 'client.js');
const HOST_CONTRACT = path.join(ROOT, 'src', 'generated-verb-contract.ts');
const BEGIN = '// >>> houdini-catalog (generated by tools/gen-client-catalog.mjs — do not edit)';
const END = '// <<< houdini-catalog';

const catalog = loadCatalog(DOC).map((d) => ({
  domain: d.domain,
  note: d.note,
  verbs: d.verbs.map((v) => ({ name: v.name, sig: v.sig, desc: v.desc, returns: v.returns })),
}));
const verbTotal = catalog.reduce((n, d) => n + d.verbs.length, 0);
const verbNames = catalog.flatMap((domain) => domain.verbs.map((verb) => verb.name)).sort();
const verbCatalogHash = crypto.createHash('sha256').update(verbNames.join('\n')).digest('hex');
const executionContractVersion = Number(fs.readFileSync(DOC, 'utf8').match(/^Execution contract version: (\d+)$/m)?.[1]);
if (!Number.isSafeInteger(executionContractVersion) || executionContractVersion < 1) {
  throw new Error('docs/tool-design.md must declare Execution contract version: <positive integer>');
}

const src = fs.readFileSync(CLIENT, 'utf8');
const begin = src.indexOf(BEGIN);
const end = src.indexOf(END);
if (begin === -1 || end === -1 || end < begin) {
  console.error('client.js 里找不到 catalog 标记区（>>> houdini-catalog / <<< houdini-catalog）');
  process.exit(1);
}
const block = `${BEGIN}\n    var CATALOG = ${JSON.stringify(catalog)};\n    ${END}`;
const next = src.slice(0, begin) + block + src.slice(end + END.length);
if (next === src) {
  console.log(`client.js catalog unchanged (${catalog.length} domains, ${verbTotal} verbs)`);
} else {
  fs.writeFileSync(CLIENT, next);
  console.log(`client.js catalog updated: ${catalog.length} domains, ${verbTotal} verbs`);
}

const contractSource = `// Generated by tools/gen-client-catalog.mjs from docs/tool-design.md. Do not edit.\n`
  + `export const EXPECTED_VERB_NAMES = ${JSON.stringify(verbNames)} as const\n`
  + `export const EXPECTED_VERB_CATALOG_HASH = ${JSON.stringify(verbCatalogHash)}\n`
  + `export const EXPECTED_EXECUTION_CONTRACT_VERSION = ${executionContractVersion}\n`
  + `export const VERB_CATALOG_SUMMARY = ${JSON.stringify(catalog.map((domain) => `${domain.domain}: ${domain.verbs.map((verb) => verb.name).join(', ')}`).join(' | '))}\n`;
const previousContract = fs.existsSync(HOST_CONTRACT) ? fs.readFileSync(HOST_CONTRACT, 'utf8') : '';
if (previousContract === contractSource) {
  console.log(`host verb contract unchanged (${verbTotal} verbs, ${verbCatalogHash.slice(0, 12)})`);
} else {
  fs.writeFileSync(HOST_CONTRACT, contractSource);
  console.log(`host verb contract updated: ${verbTotal} verbs, ${verbCatalogHash.slice(0, 12)}`);
}
